CODES = MappingProxyType(dict(_CODE_PAIRS))
ERROR_CODES = tuple(CODES.values())
CODE = CODES


class ShellCageError(ValueError):
    """A validation, policy, configuration, or spawn failure.

    The stable machine-readable code is available as ``code``. Details are
    defensive metadata only and must never contain environment or secret
    values.
    """

    def __init__(self, code: str, message: str, details: Optional[Mapping[str, Any]] = None) -> None:
        self.code = str(code)
        self.message = str(message)
        source = dict(details or {})
        self.details = MappingProxyType(source)
        super().__init__(self.code + ": " + self.message)

    def to_dict(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "message": self.message,
            "details": dict(self.details),
        }


def fail(code: str, message: str, details: Optional[Mapping[str, Any]] = None) -> None:
    raise ShellCageError(code, message, details)
